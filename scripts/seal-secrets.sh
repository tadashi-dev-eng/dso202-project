#!/usr/bin/env bash
# scripts/seal-secrets.sh -- TaskFlow (DSO202 final project)
#
# Turns the credential files in ~/.taskflow-keys into SealedSecrets that are
# safe to commit: they are encrypted with the cluster's Sealed Secrets public
# key and can only be decrypted by that controller, inside the cluster, for
# the namespace and name they were sealed for.
#
#   bash scripts/seal-secrets.sh
#
# Writes:
#   deploy/environments/overlays/<env>/sealed-secrets.yaml   per environment
#   deploy/platform-secrets/<namespace>.yaml                 TLS (+ admin logins)
#
# Before the first run, back up the controller's private key (otherwise a
# rebuilt cluster can never decrypt what is in Git):
#   kubectl get secret -n sealed-secrets -l sealedsecrets.bitnami.com/sealed-secrets-key \
#     -o yaml > ~/.taskflow-keys/sealed-secrets-key.backup.yaml
set -euo pipefail
cd "$(dirname "$0")/.."
KEYS="${TASKFLOW_KEYS:-$HOME/.taskflow-keys}"
K="$KEYS"
command -v cygpath >/dev/null 2>&1 && K="$(cygpath -m "$KEYS")"
SEAL=(kubeseal --controller-namespace sealed-secrets --controller-name sealed-secrets-controller --format yaml)

header() {
  printf '# %s -- generated by scripts/seal-secrets.sh. Encrypted for this\n' "$1"
  printf '# cluster'"'"'s Sealed Secrets controller; safe to commit. Plaintext\n'
  printf '# sources live in ~/.taskflow-keys, never in the repository.\n'
}

# split a multi-document YAML stream on stdin and seal each document
seal_stream() {
  python -I -c '
import sys, subprocess
docs = [d for d in sys.stdin.read().split("\n---\n") if d.strip()]
out = []
for d in docs:
    r = subprocess.run(sys.argv[1:], input=d.encode(), capture_output=True)
    if r.returncode:
        sys.stderr.write(r.stderr.decode()); sys.exit(1)
    out.append(r.stdout.decode().strip())
print("\n---\n".join(out))
' "${SEAL[@]}"
}

for env in dev prod; do
  ns="taskflow-$env"
  out="deploy/environments/overlays/$env/sealed-secrets.yaml"
  { header "$out"; RENDER=1 bash scripts/make-secrets.sh "$ns" 2>/dev/null | seal_stream; } > "$out"
  echo "sealed $(grep -c '^kind: SealedSecret' "$out") secrets -> $out"
done

mkdir -p deploy/platform-secrets
for ns in argocd observability cicd; do
  out="deploy/platform-secrets/$ns.yaml"
  {
    header "$out"
    {
      kubectl create secret tls taskflow-tls -n "$ns" --cert="$K/tls.crt" --key="$K/tls.key" \
        --dry-run=client -o yaml
      if [ "$ns" = observability ] && [ -f "$KEYS/grafana-admin" ]; then
        echo "---"
        kubectl create secret generic grafana-admin -n "$ns" \
          --from-literal=admin-user=admin --from-file=admin-password="$K/grafana-admin" \
          --dry-run=client -o yaml
      fi
      if [ "$ns" = cicd ] && [ -f "$KEYS/jenkins-admin" ]; then
        echo "---"
        kubectl create secret generic jenkins-admin -n "$ns" \
          --from-literal=jenkins-admin-user=admin --from-file=jenkins-admin-password="$K/jenkins-admin" \
          --dry-run=client -o yaml
      fi
      if [ "$ns" = cicd ] && [ -f "$KEYS/github-deploy-key" ]; then
        echo "---"
        kubectl create secret generic github-deploy-key -n "$ns" \
          --from-file=ssh-privatekey="$K/github-deploy-key" --dry-run=client -o yaml
      fi
    } | seal_stream
  } > "$out"
  echo "sealed $(grep -c '^kind: SealedSecret' "$out") secrets -> $out"
done
